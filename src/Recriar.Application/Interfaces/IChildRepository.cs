using Recriar.Domain.Entities;

namespace Recriar.Application.Interfaces;

/// <summary>
/// Contract for saving and reading children in the database.
/// Implemented by the database project (Recriar.Infrastructure/Persistence/Repositories).
/// </summary>
// "interface": lista os métodos que alguém TEM que implementar, sem dizer como.
// É como os protótipos de função no topo de um arquivo em C (ex.: "void salvarDados();").
public interface IChildRepository
{
    /// <summary>
    /// Finds a child by id, or returns null when it does not exist.
    /// Must bring the related data together: Guardian, EmergencyContact and FamilyMembers
    /// (each family member with its RelationshipType).
    /// </summary>
    Child? GetById(int id);

    /// <summary>
    /// Returns every child, ordered by Id (the same order the C list used).
    /// The related data (guardian, contact, family) is not needed here.
    /// </summary>
    List<Child> GetAll();

    /// <summary>
    /// Returns the children whose name contains the given text, ignoring upper and lower case.
    /// (C: pesquisarPorNome, which used strstr on the lower case text). The related data is not needed.
    /// </summary>
    List<Child> SearchByName(string name);

    /// <summary>
    /// Saves a new child with everything inside it (guardian, contact and family members).
    /// After this call, child.Id (and the Ids of the inner objects) must be filled with the numbers generated by the database.
    /// </summary>
    void Add(Child child);

    /// <summary>
    /// Makes the database equal to the received child, including the inner data:
    /// guardian and contact are updated, new family members are inserted,
    /// changed ones are updated and the ones that are no longer in the list are removed.
    /// </summary>
    void Update(Child child);

    /// <summary>
    /// Deletes the child and everything that belongs to it (guardian, contact and family members).
    /// Returns false when the id does not exist. (C: excluirCadastro)
    /// </summary>
    bool Delete(int id);
}
